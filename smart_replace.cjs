const fs = require('fs');

function replaceLines(file, replacements) {
  let c = fs.readFileSync(file, 'utf8');
  for (let [b, g] of replacements) {
    c = c.replace(b, g);
  }
  fs.writeFileSync(file, c, 'utf8');
}


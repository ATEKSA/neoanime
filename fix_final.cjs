const fs = require('fs');

function fix(f, replacements) {
  let c = fs.readFileSync(f, 'utf8');
  for (let [b, g] of replacements) {
    c = c.split(b).join(g);
  }
  fs.writeFileSync(f, c, 'utf8');
}


const fs = require('fs');

function fixLayout() {
  let c = fs.readFileSync('src/Layout.jsx', 'utf8');

  c = c.replace(/<span className=\"login-text\">\?\?\?\?\?\?<\/span>/g, '<span className="login-text">Профиль</span>');
  c = c.replace(/<button className=\"btn-premium\" onClick=\{\(\) => showToast\(\'\?\?\?\?\?\?\? \?\?\?\?\?\?\? \?\?\?\? \? \?\?\?\?\?\?\?\?\?\!\'\)\}>/g, "<button className=\"btn-premium\" onClick={() => showToast('Функция Premium пока в разработке!')}>");
  c = c.replace(/<label>\?\?\?\?\?\? \?\?\?\?\?\?\?\?\?\?\?\?\?<\/label>/g, '<label>Логин или Email</label>');
  c = c.replace(/<label>\?\?\?\?\?\?<\/label>/g, '<label>Пароль</label>');
  c = c.replace(/placeholder=\"\?\?\? \?\?\?\?\?\?\"/g, 'placeholder="Ваш пароль"');
  c = c.replace(/\{authMode === \'login\' \? \'\?\?\?\?\?\' \: \'\?\?\?\?\?\?\?\?\?\?\'\}/g, "{authMode === 'login' ? 'Войти' : 'Регистрация'}");
  c = c.replace(/<>\?\?\? \?\?\?\?\?\?\?\? <span onClick=\{\(\) => \{ setAuthMode\(\'register\'\); setAuthError\(\'\'\); \}\}>\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?\?<\/span><\/>/g, "<>Нет аккаунта? <span onClick={() => { setAuthMode('register'); setAuthError(''); }}>Зарегистрироваться</span></>");
  c = c.replace(/<>\?\?\? \?\?\?\? \?\?\?\?\?\?\?\? <span onClick=\{\(\) => \{ setAuthMode\(\'login\'\); setAuthError\(\'\'\); \}\}>\?\?\?\?\?<\/span><\/>/g, "<>Уже есть аккаунт? <span onClick={() => { setAuthMode('login'); setAuthError(''); }}>Войти</span></>");
  c = c.replace(/>\?\?\?\?\?\?\?\?\ \?\?\ \?\?\?\?\?\?\?\?</g, ">Ничего не найдено<");
  c = c.replace(/>\?\?\?\?\?\?\?\?\?\ \?\?\?\ \?\?\?\?\?\?\?\?\?\ \?\?\?\?\?\?\?\?\?\?\</g, ">Смотреть все результаты поиска<");

  fs.writeFileSync('src/Layout.jsx', c, 'utf8');
}

fixLayout();

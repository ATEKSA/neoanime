const fs = require('fs');

function fixFile(path, fixes) {
  let c = fs.readFileSync(path, 'utf8');
  for (const [bad, good] of fixes) {
    c = c.replace(bad, good);
  }
  fs.writeFileSync(path, c, 'utf8');
}

